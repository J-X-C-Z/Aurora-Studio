/// Position on a sorted axis: `(index, fraction)` clamped to the ends.
fn locate(axis: &[f32], value: f32) -> (usize, f32) {
    let value = value.clamp(axis[0], axis[axis.len() - 1]);
    let mut i = 0;
    while i + 2 < axis.len() && value > axis[i + 1] {
        i += 1;
    }
    let span = axis[i + 1] - axis[i];
    (i, if span > 0.0 { ((value - axis[i]) / span).clamp(0.0, 1.0) } else { 0.0 })
}

fn kelvin_at(x: f32) -> f32 {
    let (i, f) = locate(&WB_X, x);
    WB_K[i] + (WB_K[i + 1] - WB_K[i]) * f
}

fn tint_at(x: f32, v: f32) -> f32 {
    let (i, fx) = locate(&WB_X, x);
    let (j, fv) = locate(&WB_V, v);
    let top = WB_T[i][j] + (WB_T[i + 1][j] - WB_T[i][j]) * fx;
    let bottom = WB_T[i][j + 1] + (WB_T[i + 1][j + 1] - WB_T[i][j + 1]) * fx;
    top + (bottom - top) * fv
}

/// C1's `IC_RGBToKelvinTint` for a Nikon Z6III, by table interpolation.
///
/// Input is the stored `r;g;b` gain triple. Invalid gains fall back to the
/// engine's old reference pair so callers never see NaN.
pub fn gains_to_kelvin_tint(gains: [f32; 3]) -> (f32, f32) {
    let (r, g, b) = (gains[0], gains[1], gains[2]);
    if !(r > 0.0 && g > 0.0 && b > 0.0) || !r.is_finite() || !g.is_finite() || !b.is_finite() {
        return (5600.0, 0.0);
    }
    let x = (r / b).ln();
    let v = (b / g).ln();
    (kelvin_at(x), tint_at(x, v))
}

/// Inverse of [`gains_to_kelvin_tint`] with green pinned at 1, matching C1's
/// `IC_KelvinTintToRGB` output for the sampled camera.
pub fn kelvin_tint_to_gains(kelvin: f32, tint: f32) -> [f32; 3] {
    if !kelvin.is_finite() || !tint.is_finite() {
        return [1.0, 1.0, 1.0];
    }
    let (mut x_lo, mut x_hi) = (WB_X[0], WB_X[WB_X.len() - 1]);
    let mut v = 0.0;
    for _ in 0..40 {
        let x = (x_lo + x_hi) * 0.5;
        let (mut v_lo, mut v_hi) = (WB_V[0], WB_V[WB_V.len() - 1]);
        for _ in 0..40 {
            let mid = (v_lo + v_hi) * 0.5;
            if tint_at(x, mid) < tint {
                v_lo = mid;
            } else {
                v_hi = mid;
            }
        }
        v = (v_lo + v_hi) * 0.5;
        if kelvin_at(x) < kelvin {
            x_lo = x;
        } else {
            x_hi = x;
        }
    }
    let x = (x_lo + x_hi) * 0.5;
    [(x + v).exp(), 1.0, v.exp()]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_c1_on_the_three_reference_frames() {
        for (gains, kelvin, tint) in [
            ([1.922, 1.0, 1.285], 5891.29, 1.10849),
            ([1.912, 1.0, 1.357], 5593.11, 3.17621),
            ([1.625, 1.0, 1.412], 4779.55, -4.4875),
        ] {
            let (k, t) = gains_to_kelvin_tint(gains);
            assert!((k - kelvin).abs() < 10.0, "{gains:?}: {k} vs {kelvin}");
            assert!((t - tint).abs() < 0.2, "{gains:?}: {t} vs {tint}");
        }
    }

    #[test]
    fn inverse_recovers_the_reference_gains() {
        for (gains, kelvin, tint) in [
            ([1.922, 1.0, 1.285], 5891.29, 1.10849),
            ([1.625, 1.0, 1.412], 4779.55, -4.4875),
        ] {
            let back = kelvin_tint_to_gains(kelvin, tint);
            assert!((back[0] - gains[0]).abs() < 4e-3, "{back:?} vs {gains:?}");
            assert!((back[2] - gains[2]).abs() < 4e-3, "{back:?} vs {gains:?}");
            assert_eq!(back[1], 1.0);
        }
    }

    #[test]
    fn tint_is_monotonic_in_green() {
        let mut previous = f32::NEG_INFINITY;
        for v in WB_V {
            let tint = tint_at(0.2, v);
            assert!(tint >= previous, "{v}: {tint} < {previous}");
            previous = tint;
        }
    }
}
