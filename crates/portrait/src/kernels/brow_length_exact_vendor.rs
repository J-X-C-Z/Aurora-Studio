/// Clamp a slider value into `[0, 1]` (the config's first/last knots).
fn clamp_unit(value: f32) -> f32 {
    if value < 0.0 {
        0.0
    } else if value > 1.0 {
        1.0
    } else {
        value
    }
}

/// Three-node piecewise-linear remap, exactly as `RenderParamRanges` defines.
///
/// `ui` must already be clamped into `[0, 1]`. The two segments are evaluated
/// with one division each, matching the vendor control curve.
fn remap_three(ui: f32, params: [f32; 3], degrees: [f32; 3]) -> f32 {
    let (left, right) = if ui <= params[1] { (0usize, 1usize) } else { (1usize, 2usize) };
    let span = params[right] - params[left];
    let t = (ui - params[left]) / span;
    degrees[left] + (degrees[right] - degrees[left]) * t
}

/// Resolve the internal degree of one `(part, control index)` at slider `ui`.
///
/// The short part returns only negative degrees and the long part only
/// positive ones; `ui == 0.5` returns exactly `0.0` for both. Finite `ui`
/// outside `[0, 1]` is clamped to the proven knot range; NaN / infinity is
/// refused. The long-part head factor is applied after the remap.
pub fn part_degree(part: BrowPart, control_index: usize, ui: f32) -> Result<f32, BrowError> {
    if !ui.is_finite() {
        return Err(BrowError::NonFinite("brow_ui"));
    }
    let range = part.degree_range(control_index)?;
    let degree = remap_three(clamp_unit(ui), RENDER_PARAM_RANGES, range);
    let factor = if part == BrowPart::Long && control_index < 2 {
        HEAD_LONG_DEGREE_FACTOR
    } else {
        1.0
    };
    Ok(degree * factor)
}

/// Both parts' degrees for one control index at the same slider value.
///
/// Below `0.5` only the short part moves (negative), above `0.5` only the
/// long part (positive), and exactly `0.5` is a bit-exact zero for both.
pub fn part_pair(control_index: usize, ui: f32) -> Result<[f32; 2], BrowError> {
    Ok([
        part_degree(BrowPart::Short, control_index, ui)?,
        part_degree(BrowPart::Long, control_index, ui)?,
    ])
}

/// The vendor's per-side visibility gate: a tail degree is cleared when the
/// frame visibility drops below `0.5`. NaN compares false and therefore
/// clears, matching the unordered `comiss`/`jbe` in the vendor path.
pub fn gate_tail_degree(tail_degree: f32, visibility: f32) -> f32 {
    if visibility >= VISIBILITY_GATE {
        tail_degree
    } else {
        0.0
    }
}

