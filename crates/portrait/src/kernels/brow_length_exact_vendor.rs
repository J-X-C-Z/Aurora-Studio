/// Direction of one 4-ring (96-vertex) brow side (`PROVEN`, `0x707EA60` / `0x707ED50`).
///
/// * `A` = left brow (`0..96`): active rings `0/24/48`, zero-displacement anchor ring `72..96`.
/// * `B` = right brow (`96..192`, `object+0x5c = 0x60 = 96`): active rings `96/120/144`,
///   zero-displacement anchor ring `168..192`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BrowDirection {
    A,
    B,
}

impl BrowDirection {
    /// Buffer offset used for both the Ring-0 source window and the side's 4 rings.
    pub const fn base(self) -> usize {
        match self {
            BrowDirection::A => 0,
            BrowDirection::B => SIDE_VERTEX_COUNT,
        }
    }

    /// Physical brow side (`A = Left`, `B = Right`, `PROVEN`).
    pub const fn side(self) -> BrowSide {
        match self {
            BrowDirection::A => BrowSide::Left,
            BrowDirection::B => BrowSide::Right,
        }
    }

    /// Vertex index range of the zero-displacement Ring 3 outer border anchor ring.
    pub const fn anchor_ring_range(self) -> std::ops::Range<usize> {
        let start = self.base() + ANCHOR_RING_INDEX * RING_VERTICES;
        start..(start + RING_VERTICES)
    }
}

/// One direction's anchor segment plus its separate projection center.
///
/// The vendor reads `center` from `guide[+0x20]` (point 4), `start` from
/// `guide[0]` and `end` from `guide[+0x40]` (point 8). They are distinct
/// fields on purpose: `center` is not recomputed as a midpoint.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct BrowGuide {
    pub start: Point,
    pub end: Point,
    pub center: Point,
}

impl BrowGuide {
    /// Read `[0]`, `[4]`, `[8]` from a 24-point guide array.
    pub fn from_centerline(guide: &[Point]) -> Result<Self, BrowError> {
        if guide.len() < 9 {
            return Err(BrowError::GuideLength {
                want: 9,
                got: guide.len(),
            });
        }
        Ok(Self {
            start: guide[0],
            end: guide[8],
            center: guide[4],
        })
    }

    /// `(normalize(end - start), 0.5 * |end - start|)`.
    fn axis(self) -> Result<(Point, f32), BrowError> {
        if !self.start.finite() || !self.end.finite() || !self.center.finite() {
            return Err(BrowError::NonFinite("brow_guide"));
        }
        let span = self.end.sub(self.start);
        let length = span.length();
        if !(length > 0.0) || !length.is_finite() {
            return Err(BrowError::DegenerateAxis("brow_guide_segment"));
        }
        let inv = 1.0 / length;
        Ok((Point::new(span.x * inv, span.y * inv), length * 0.5))
    }
}

/// Per-direction head / tail degrees. The consumer keeps four scalar degrees
/// (head and tail per direction) and mixes them with the projection sign.
#[derive(Clone, Copy, Debug, PartialEq, Default)]
pub struct BrowDirectionDegrees {
    pub head: f32,
    pub tail: f32,
}

/// Everything the numeric consumer needs for one part.
pub struct BrowLengthInputs<'a> {
    pub part: BrowPart,
    /// 192-point immutable source buffer (`0..96` left brow 4×24, `96..192` right brow 4×24).
    pub source: &'a [Point],
    pub guide_a: BrowGuide,
    pub guide_b: BrowGuide,
    pub degrees_a: BrowDirectionDegrees,
    pub degrees_b: BrowDirectionDegrees,
    /// `S` returned by the vendor helper `0x707F260` (landmark distance).
    pub scale: f32,
}

/// One numeric vertex: unaffected source position, warped target position,
/// and the ring coefficient that was applied.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct BrowVertex {
    /// Index in the 192-point mesh buffer (`0..72` left active, `96..168` right active).
    pub slot: usize,
    pub source: Point,
    pub target: Point,
    pub coefficient: f32,
}

impl BrowVertex {
    const EMPTY: BrowVertex = BrowVertex {
        slot: 0,
        source: Point::ZERO,
        target: Point::ZERO,
        coefficient: 0.0,
    };

    /// Source position normalised by a caller-supplied frame size
    /// (matches `0x4C976F0` `src_pts *= (1/W, 1/H)`).
    pub fn source_uv(&self, frame: [f32; 2]) -> [f32; 2] {
        [self.source.x / frame[0], self.source.y / frame[1]]
    }

    /// Warped position in the numeric (pixel) domain.
    pub fn target_pixels(&self) -> [f32; 2] {
        [self.target.x, self.target.y]
    }
}

/// One of the six 24-vertex active windows (Ring 0/1/2 per side).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct BrowWindow {
    pub direction: BrowDirection,
    /// Ring index `0..=2`; selects the coefficient array (Ring 3 is anchored at zero displacement).
    pub ring: usize,
    /// Offset of vertex 0 in the 192-point mesh buffer (`0/24/48` left, `96/120/144` right).
    pub target_base: usize,
    pub vertices: [BrowVertex; RING_VERTICES],
}

/// Result of one part's numeric pass.
#[derive(Clone, Debug, PartialEq)]
pub struct BrowLengthMesh {
    /// Untouched 192-point source buffer (left `0..96`, right `96..192`).
    pub source: Vec<Point>,
    /// Warped 192-point target buffer; Ring 3 (`72..96` left, `168..192` right) is
    /// bit-identical to `source` (zero-displacement outer border anchor ring).
    pub target: Vec<Point>,
    /// Six active windows in native write order: A (left) rings 0/1/2, then B (right) rings 0/1/2.
    pub windows: Vec<BrowWindow>,
    /// `half` of direction A and B.
    pub half: [f32; 2],
    /// Head / tail degrees of direction A and B, as supplied.
    pub degrees: [BrowDirectionDegrees; 2],
    /// True when every target coordinate is bit-identical to its source.
    pub noop: bool,
}

impl BrowLengthMesh {
    /// All 144 numeric vertices in native write order.
    pub fn vertices(&self) -> impl Iterator<Item = &BrowVertex> {
        self.windows.iter().flat_map(|window| window.vertices.iter())
    }
}

/// Apply the recovered `0x707ED50` numeric warp to one part.
///
/// Formula, in the vendor's own evaluation order:
///
/// ```text
/// dir     = normalize(end - start)
/// half    = 0.5 * |end - start|
/// t       = dot(source[base + i] - center, dir)
/// u       = (half > 0.001) ? t / half : 0
/// d       = (t <= 0) ? head : tail
/// w       = ((d * 0.8) * u) * S
/// target[base + ring*24 + i] += (C[ring][i] * w) * dir
/// ```
///
/// A zero `w` is skipped so a zero degree leaves the source bits untouched.
pub fn build(inputs: BrowLengthInputs<'_>) -> Result<BrowLengthMesh, BrowError> {
    if inputs.source.len() != NUMERIC_BUFFER_POINTS {
        return Err(BrowError::BufferLength {
            want: NUMERIC_BUFFER_POINTS,
            got: inputs.source.len(),
        });
    }
    if !inputs.source.iter().all(|point| point.finite())
        || !inputs.degrees_a.head.is_finite()
        || !inputs.degrees_a.tail.is_finite()
        || !inputs.degrees_b.head.is_finite()
        || !inputs.degrees_b.tail.is_finite()
        || !inputs.scale.is_finite()
    {
        return Err(BrowError::NonFinite("brow_length_inputs"));
    }
    if inputs.scale < 0.0 {
        return Err(BrowError::OutOfRange("brow_length_scale"));
    }

    let tables = inputs.part.tables();
    let (axis_a, half_a) = inputs.guide_a.axis()?;
    let (axis_b, half_b) = inputs.guide_b.axis()?;

    let directions = [
        (BrowDirection::A, inputs.guide_a, axis_a, half_a, inputs.degrees_a),
        (BrowDirection::B, inputs.guide_b, axis_b, half_b, inputs.degrees_b),
    ];

    // Pass 1: copy 192 source vertices (matching `0x707E820` memcpy) so Ring 3
    // (`72..96` left, `168..192` right) stays anchored at zero displacement,
    // then accumulate Ring 0/1/2 displacements into the disjoint left (`0..72`)
    // and right (`96..168`) windows.
    let mut target = inputs.source.to_vec();
    for (direction, guide, axis, half, degrees) in directions {
        let base = direction.base();
        for ring in 0..RINGS_PER_DIRECTION {
            let coefficients = tables.ring(ring)?;
            let offset = base + ring * RING_VERTICES;
            for i in 0..RING_VERTICES {
                let from = inputs.source[base + i];
                let t = from.sub(guide.center).dot(axis);
                let u = if half > HALF_EPSILON { t / half } else { 0.0 };
                let d = if t <= 0.0 { degrees.head } else { degrees.tail };
                let w = d * LENGTH_AMOUNT * u * inputs.scale;
                if w != 0.0 {
                    target[offset + i] = target[offset + i].add(axis.scale(w * coefficients[i]));
                }
            }
        }
    }

    // Pass 2: emit the 144 vertices against the final accumulated target.
    let mut windows = Vec::with_capacity(WINDOW_COUNT);
    for (direction, _, _, _, _) in directions {
        let base = direction.base();
        for ring in 0..RINGS_PER_DIRECTION {
            let coefficients = tables.ring(ring)?;
            let target_base = base + ring * RING_VERTICES;
            let mut vertices = [BrowVertex::EMPTY; RING_VERTICES];
            for (i, vertex) in vertices.iter_mut().enumerate() {
                *vertex = BrowVertex {
                    slot: target_base + i,
                    source: inputs.source[base + i],
                    target: target[target_base + i],
                    coefficient: coefficients[i],
                };
            }
            windows.push(BrowWindow {
                direction,
                ring,
                target_base,
                vertices,
            });
        }
    }

    let noop = inputs
        .source
        .iter()
        .zip(target.iter())
        .all(|(from, to)| {
            from.x.to_bits() == to.x.to_bits() && from.y.to_bits() == to.y.to_bits()
        });

    Ok(BrowLengthMesh {
        source: inputs.source.to_vec(),
        target,
        windows,
        half: [half_a, half_b],
        degrees: [inputs.degrees_a, inputs.degrees_b],
        noop,
    })
}

