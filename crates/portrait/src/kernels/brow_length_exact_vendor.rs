/// Reproduce the dual-side ordered `u16` triangle list generated by the
/// `Type1018` constructor at `0x707DE40` (`object+0x58 = 24`, `object+0x5c = 96`).
///
/// Per-side local topology (`498` indices over `0..=95`):
/// * 10 inner closure iterations x 6 = 60 indices;
/// * 2 center-close iterations x 3 = 6 indices;
/// * 3 ring bands (`Ring 0↔1`, `1↔2`, `2↔3`) x 24 columns x 6 = 432 indices.
///
/// Dual-side EBO (`996` indices total):
/// * `0..498`: left brow (`local`, indexing `0..=95`);
/// * `498..996`: right brow (`local + 96`, indexing `96..=191`).
pub fn type1018_ordered_ebo() -> Vec<u16> {
    const HALF: usize = RING_VERTICES / 2;
    let mut local: Vec<u16> = Vec::with_capacity(SIDE_EBO_INDEX_COUNT);

    for i in 0..(RING_VERTICES - HALF - 2) {
        let next = i + 1;
        let back = RING_VERTICES - 1 - i;
        let tail = RING_VERTICES - 2 - i;
        local.extend([
            i as u16,
            next as u16,
            back as u16,
            back as u16,
            next as u16,
            tail as u16,
        ]);
    }

    for i in (RING_VERTICES - HALF - 2)..HALF {
        local.extend([i as u16, (i + 1) as u16, (HALF + 1) as u16]);
    }

    for band in 0..3 {
        let top = band * RING_VERTICES;
        let bottom = (band + 1) * RING_VERTICES;
        for column in 0..RING_VERTICES {
            let next = (column + 1) % RING_VERTICES;
            local.extend([
                (top + column) as u16,
                (top + next) as u16,
                (bottom + column) as u16,
                (bottom + column) as u16,
                (top + next) as u16,
                (bottom + next) as u16,
            ]);
        }
    }

    debug_assert_eq!(local.len(), SIDE_EBO_INDEX_COUNT);
    let mut out = Vec::with_capacity(EBO_INDEX_COUNT);
    out.extend_from_slice(&local);
    out.extend(local.iter().map(|&index| index + SIDE_VERTEX_COUNT as u16));
    debug_assert_eq!(out.len(), EBO_INDEX_COUNT);
    out
}

