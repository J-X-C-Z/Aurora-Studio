/// 2-D point in the vendor numeric domain (pixel space by contract).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Point {
    pub x: f32,
    pub y: f32,
}

impl Point {
    pub const ZERO: Point = Point { x: 0.0, y: 0.0 };

    pub const fn new(x: f32, y: f32) -> Self {
        Self { x, y }
    }

    pub fn finite(self) -> bool {
        self.x.is_finite() && self.y.is_finite()
    }

    fn add(self, other: Point) -> Point {
        Point::new(self.x + other.x, self.y + other.y)
    }

    fn sub(self, other: Point) -> Point {
        Point::new(self.x - other.x, self.y - other.y)
    }

    fn scale(self, factor: f32) -> Point {
        Point::new(self.x * factor, self.y * factor)
    }

    fn dot(self, other: Point) -> f32 {
        self.x * other.x + self.y * other.y
    }

    fn length(self) -> f32 {
        (self.x * self.x + self.y * self.y).sqrt()
    }
}

/// Typed refusal. The producer never invents a replacement value.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BrowError {
    /// A required value is NaN or infinite.
    NonFinite(&'static str),
    /// A value is finite but outside its proven domain.
    OutOfRange(&'static str),
    /// The numeric point buffer must hold exactly [`NUMERIC_BUFFER_POINTS`].
    BufferLength { want: usize, got: usize },
    /// A 24-point guide array is too short.
    GuideLength { want: usize, got: usize },
    /// A direction segment has zero length, so it cannot define an axis.
    DegenerateAxis(&'static str),
}

impl std::fmt::Display for BrowError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            BrowError::NonFinite(what) => write!(f, "non-finite value: {what}"),
            BrowError::OutOfRange(what) => write!(f, "value out of range: {what}"),
            BrowError::BufferLength { want, got } => {
                write!(f, "point buffer must hold {want} points, got {got}")
            }
            BrowError::GuideLength { want, got } => {
                write!(f, "guide must hold at least {want} points, got {got}")
            }
            BrowError::DegenerateAxis(what) => write!(f, "degenerate axis: {what}"),
        }
    }
}

impl std::error::Error for BrowError {}

