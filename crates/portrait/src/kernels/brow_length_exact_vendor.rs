/// `FacialRefinePart[15]` (short) or `[16]` (long).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BrowPart {
    Short,
    Long,
}

impl BrowPart {
    /// Index into the config `FacialRefinePart` array.
    pub const fn facial_refine_index(self) -> usize {
        match self {
            BrowPart::Short => 15,
            BrowPart::Long => 16,
        }
    }

    /// The proven coefficient tables of this part.
    pub fn tables(self) -> &'static BrowPartTables {
        match self {
            BrowPart::Short => &SHORT_TABLES,
            BrowPart::Long => &LONG_TABLES,
        }
    }

    /// Degree range of a control index for this part.
    pub fn degree_range(self, control_index: usize) -> Result<[f32; 3], BrowError> {
        let ranges = match self {
            BrowPart::Short => &SHORT_DEGREE_RANGES,
            BrowPart::Long => &LONG_DEGREE_RANGES,
        };
        ranges
            .get(control_index)
            .copied()
            .ok_or(BrowError::OutOfRange("brow_control_index"))
    }
}

/// The three 24-float arrays read by the consumer from `object+0x60`,
/// `+0x78`, `+0x90`.
///
/// Config layout (`PROVEN`, `0x707F170` vtable `+0x08`): `ParamList[0..24]`
/// feeds Ring 0 (`object+0x60`), `FactorList[0..24]` feeds Ring 1
/// (`object+0x78`), and `FactorList[24..48]` feeds Ring 2 (`object+0x90`).
/// Ring 3 is the zero-displacement outer border anchor ring.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct BrowPartTables {
    pub param_list: [f32; 24],
    pub factor_list: [f32; 48],
}

impl BrowPartTables {
    /// Ring coefficients: `0 -> ParamList`, `1 -> FactorList[0..24]`,
    /// `2 -> FactorList[24..48]`.
    pub fn ring(&self, ring: usize) -> Result<[f32; 24], BrowError> {
        let mut out = [0.0f32; 24];
        match ring {
            0 => out.copy_from_slice(&self.param_list),
            1 => out.copy_from_slice(&self.factor_list[..24]),
            2 => out.copy_from_slice(&self.factor_list[24..]),
            _ => return Err(BrowError::OutOfRange("coefficient_ring")),
        }
        Ok(out)
    }
}

