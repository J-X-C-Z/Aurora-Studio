//! Vendor-exact brow head / tail length producer.
//!
//! Scope: PixelCake `FaceSurgery/V2` `FacialRefinePart[15]` (short) and
//! `[16]` (long), both `Type == 1018`. Pure `std` only: zero external crates,
//! zero `unsafe`, zero file IO, zero environment reads.
//!
//! Build and test:
//!
//! ```text
//! rustc --edition 2021 --test brow_length_exact_vendor.rs
//! ```
//!
//! # What is PROVEN here
//!
//! * Config binding and every constant, decoded from
//!   `FaceSurgery/V2/effect.json` (`FacialRefinePart[15]` / `[16]`):
//!   four control slots `44124/48019/49221/41922`, `RenderParamRanges`
//!   `[0,0.5,1]`, `RenderDegreeRanges` (`[-1,0,0]` head short, `[0,0,1]`
//!   head long, `[-1.6,0,0]` tail short, `[0,0,1.8]` tail long), the long-head
//!   `DegreeFactor = 1.100000023841858` (`0x3F8CCCCD`), `DefaultDegree = 0.5`,
//!   `DefaultDegreeList = [1,1,1,1]`, `EnableDymGrid = false`,
//!   `ConservativeEffect = false`, and the per-part coefficient tables
//!   `ParamList` (24) + `FactorList` (48) used as the three 24-float arrays.
//! * The numeric consumer at `0x707ED50` (disassembly in
//!   `90_work/lanes/portrait-parse/wl38-brow-topology/evidence/`):
//!   `dir = normalize(end - start)`, `half = 0.5 * len`,
//!   `u = (half > 0.001) ? t / half : 0`,
//!   `d = (t <= 0) ? head : tail`,
//!   `w = ((d * 0.8) * u) * S`, `delta = (C[ring][i] * w) * dir`,
//!   `target += delta`. Constants read back from the binary:
//!   `0.8` @ `0x9059804`, `0.5` @ `0x8E2A3AC`, `1.0` @ `0x8E2A3B0`,
//!   `0.0010000000474974513` @ `0x8E60B20`.
//! * Layout (`PROVEN`, `0x707DE40` `movabs rax, 0x6000000018; mov [rcx+0x58], rax`
//!   + `brow-exact-closeout-20261126/REPORT.md`): `object+0x58 = 0x18 = 24`
//!   (ring length), `object+0x5c = 0x60 = 96` (4 rings x 24 vertices per side).
//!   Total mesh vertex count is `2 * 96 = 192` with completely disjoint sides:
//!   Direction A (left brow) owns `0..96` (active rings 0/1/2 at `0/24/48`,
//!   zero-displacement outer border anchor ring 3 at `72..96`);
//!   Direction B (right brow) owns `96..192` (active rings 0/1/2 at `96/120/144`,
//!   zero-displacement outer border anchor ring 3 at `168..192`).
//!   Each side reads an immutable source buffer at its own base (`0` or `96`),
//!   and all three active rings project the same 24-point Ring-0 source window.
//!   That is 6 active windows x 24 vertices = 144 displaced vertices plus
//!   2 x 24 = 48 anchored border vertices over the 192-point buffer.
//! * Coefficient table binding (`PROVEN`, `0x707F170` vtable `+0x08`):
//!   `ParamList[0..24] -> object+0x60` (Ring 0),
//!   `FactorList[0..24] -> object+0x78` (Ring 1),
//!   `FactorList[24..48] -> object+0x90` (Ring 2).
//! * The `Type1018` ordered EBO generated by `0x707DE40`: 996 `u16` total
//!   (`2 * 498`), left brow `0..498` indexing `0..=95`, right brow `498..996`
//!   indexing `local + 96` (`96..=191`), referencing all 192 vertices.
//!
//! # What is NOT proven (and therefore not invented)
//!
//! * The final shader GLSL source (`[cell+0x270]->vtable[0x120]` displacement
//!   field rasteriser and `[cell+0x280]` resampler, plus Shader ID `0x41`/`0x42`),
//!   exact VBO attribute layout and GL blend state are OPEN (`LIVE_ONLY`).
//!   `source_uv()` only normalises the source point by a caller-supplied frame
//!   size (matching `0x4C976F0` `src_pts *= (1/W, 1/H)`).

