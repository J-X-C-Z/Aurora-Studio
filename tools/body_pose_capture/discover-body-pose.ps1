[CmdletBinding()]
param(
    [string[]]$ModelRoots = @(
        "$env:ProgramFiles\Capture One\Capture One\AIModels",
        "$env:ProgramFiles\PixCake\pixcake_2\AIModels"
    ),
    [string]$OutFile = (Join-Path ([IO.Path]::GetTempPath()) "aurora-body-pose-capture\discovery.json"),
    [switch]$RequireModel
)

$ErrorActionPreference = "Stop"
$candidatePattern = "pose|body|keypoint|skeleton"
$models = New-Object System.Collections.Generic.List[object]
$scannedRoots = New-Object System.Collections.Generic.List[object]

foreach ($root in $ModelRoots) {
    if (-not (Test-Path -LiteralPath $root)) {
        $scannedRoots.Add([ordered]@{ path = $root; exists = $false; onnx_files = 0 })
        continue
    }
    $onnx = @(Get-ChildItem -LiteralPath $root -Recurse -File -Filter "*.onnx" -ErrorAction SilentlyContinue)
    $scannedRoots.Add([ordered]@{ path = (Resolve-Path -LiteralPath $root).Path; exists = $true; onnx_files = $onnx.Count })
    foreach ($file in $onnx) {
        if ($file.Name -notmatch $candidatePattern) { continue }
        $sha = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
        $sidecar = "$($file.FullName).sha256"
        $declared = $null
        $sidecarValid = $false
        if (Test-Path -LiteralPath $sidecar -PathType Leaf) {
            $declared = (Get-Content -LiteralPath $sidecar -Raw).Split([char[]]" `t`r`n", [StringSplitOptions]::RemoveEmptyEntries)[0].ToLowerInvariant()
            $sidecarValid = ($declared -match "^[0-9a-f]{64}$" -and $declared -eq $sha)
        }
        $models.Add([ordered]@{
            path = $file.FullName
            bytes = $file.Length
            sha256 = $sha
            sidecar = $(if (Test-Path -LiteralPath $sidecar) { $sidecar } else { $null })
            declared_sha256 = $declared
            sidecar_valid = $sidecarValid
            tensor_contract_verified = $false
        })
    }
}

$pixcook = "$env:ProgramFiles\PixCake\pixcake_2\resources\pixcook"
$containerPresent = Test-Path -LiteralPath $pixcook -PathType Leaf
$document = [ordered]@{
    schema = "aurora/body-pose-discovery/1"
    scanned_roots = $scannedRoots
    candidate_models = $models
    pixcook = [ordered]@{
        path = $pixcook
        present = $containerPresent
        bytes = if ($containerPresent) { (Get-Item -LiteralPath $pixcook).Length } else { $null }
        format = "ustar; first header XOR key eccdcadcb"
        body_pose_model_id = $null
    }
    status = if ($models.Count -gt 0) { "candidate-requires-tensor-check" } else { "no-pose-onnx" }
    note = "No keypoint is generated by discovery. A candidate is usable only after digest and tensor-contract acceptance."
}

$directory = Split-Path -Parent $OutFile
if ($directory) { [void](New-Item -ItemType Directory -Force -Path $directory) }
$document | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath $OutFile -Encoding UTF8
Write-Host ("discovered {0} pose-named ONNX candidate(s) -> {1}" -f $models.Count, $OutFile)
if ($RequireModel -and $models.Count -eq 0) { exit 2 }
